#!/usr/bin/env bash
# Regenerates src/ui/map/world.ts: a deliberately low-detail outline of China and
# the land around it, for the game-style map. Source: Natural Earth 1:50m
# admin-0 countries (public domain, https://www.naturalearthdata.com).
set -euo pipefail
cd "$(dirname "$0")/.."
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
curl -sL -o "$tmp/ne50.geojson" \
  https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_0_countries.geojson
npx --yes mapshaper@0.6 -i "$tmp/ne50.geojson" -filter "ADMIN=='China'" -filter-fields ADMIN \
  -simplify 3% keep-shapes -filter-islands min-area=3000km2 -o "$tmp/china.json" format=geojson precision=0.01
npx --yes mapshaper@0.6 -i "$tmp/ne50.geojson" -clip bbox=55,0,155,60 -filter "ADMIN!='China'" -dissolve \
  -simplify 3% keep-shapes -filter-islands min-area=3000km2 -o "$tmp/land.json" format=geojson geojson-type=FeatureCollection precision=0.01
{
  echo '// Generated by scripts/build-world.sh — do not edit by hand.'
  echo '// Low-detail outlines from Natural Earth 1:50m admin-0 countries (public domain).'
  echo "export const world: { china: GeoJSON.FeatureCollection; land: GeoJSON.FeatureCollection } = {"
  echo "  china: $(cat "$tmp/china.json"),"
  echo "  land: $(cat "$tmp/land.json"),"
  echo "}"
} > src/ui/map/world.ts
echo "wrote src/ui/map/world.ts ($(wc -c < src/ui/map/world.ts) bytes)"
